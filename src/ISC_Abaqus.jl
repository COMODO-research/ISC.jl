function Inp3_6_Tie_Const(; file, master_set, slave_set, adjust = "yes")
    master_clean = replace(master_set, "-" => "")
    slave_clean  = replace(slave_set, "-" => "")

    master_surf = "MASTER_SURF_$master_clean"
    slave_surf  = "SLAVE_SURF_$slave_clean"
    tie_name    = "Tie-$master_clean-$slave_clean"

    println(file, "**")
    println(file, "** ====================================")
    println(file, "** TIE CONSTRAINTS")
    println(file, "** ====================================")
    println(file, "**")
    
    println(file, "*Surface, type=NODE, name=$master_surf")
    println(file, "$master_set,")

    println(file, "*Surface, type=NODE, name=$slave_surf")
    println(file, "$slave_set,")

    println(file, "** Constraint: $tie_name")
    println(file, "*Tie, name=$tie_name, adjust=$adjust")
    println(file, "$slave_surf, $master_surf")
end

