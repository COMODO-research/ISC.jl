function Inp2_Part(; file, part_name, nodes, elements, element_type, section, material)

    println(file, "**")
    println(file, "** ====================================")
    println(file, "** PART")
    println(file, "** ====================================")
    println(file, "**")
    
    println(file, "*Part, name=$part_name")
    println(file, "* Node")

    for (i, v) in enumerate(nodes)
    println(file, @sprintf("%8i, %24.16e, %24.16e, %24.16e", i, v[1], v[2], v[3]))
    end

    println(file, "*Element, type=$element_type")

    for (i, e) in enumerate(elements)
    println(file, @sprintf("%8i, %8i, %8i, %8i, %8i, %8i, %8i, %8i, %8i", i, e[1], e[2], e[3], e[4], e[5], e[6], e[7], e[8]))
    end

    println(file, "*Elset, elset=\"SET-($part_name)\", generate")
    println(file, "1,    $(length(elements)),    1")
    println(file, "** Section: $section")
    println(file, "*Solid Section, elset=\"SET-($part_name)\", material=$material")
    println(file, ",")
    println(file, "*End Part")
    println(file, "**")
end

