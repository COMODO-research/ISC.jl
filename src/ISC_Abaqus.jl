    println(file, "** ====================================")
    println(file, "** CREATE SET - INSTANCES")
    println(file, "** ====================================")
    println(file, "**")
    
    println(file, "*Nset, nset=$set_name, instance=$instance_name")

    for i in 1:chunk_size:length(set_ids)
        chunk = set_ids[i:min(i + chunk_size - 1, length(set_ids))]
        println(file, join(chunk, ", "))
    end

    println(file, "**")
end

